set -Eeuo pipefail

REV="QUANT-NOVA-2.4.22-EXACT-R19-UI-RESTORE-V13"
APP="quant-nova"
GUARD="nova-http-guard"
HOST_STATIC="/home/ubuntu/quant-nova/http-guard-v2/static"
HOST_CACHE="/home/ubuntu/quant-nova/http-guard-v2/cache"
STAMP="$(date +%Y%m%d%H%M%S)"
WORK="/tmp/nova-r19-ui-v13-$STAMP"
BK="$HOME/quant-nova/ui-r19-v13-backups"
SUCCESS=0

mkdir -p "$WORK" "$BK"
chmod 700 "$WORK" "$BK"

rollback(){
  ec=$?
  if [[ "$SUCCESS" -ne 1 ]]; then
    echo "=== V13 AUTO ROLLBACK ==="
    if [[ -d "$WORK/host-before" ]]; then
      sudo rm -rf "$HOST_STATIC"
      sudo mkdir -p "$HOST_STATIC"
      sudo cp -a "$WORK/host-before/." "$HOST_STATIC/" || true
    fi
    if [[ -d "$WORK/app-before" ]]; then
      sudo docker exec "$APP" sh -c 'rm -rf /app/static/*' || true
      sudo docker cp "$WORK/app-before/." "$APP:/app/static/" >/dev/null 2>&1 || true
    fi
    sudo find "$HOST_CACHE" -maxdepth 1 -type f \( -name '*.body' -o -name '*.json' \) -delete 2>/dev/null || true
    sudo docker restart "$GUARD" >/dev/null 2>&1 || true
    echo "ROLLBACK=COMPLETE"
  fi
  exit "$ec"
}
trap rollback ERR INT TERM

echo "=== $REV START ==="
echo "SOURCE=UPLOADED_R19_INSTALLER_EXACT_STATIC"
echo "SOURCE_R19_ZIP_SHA256=f8fc45e7583347b3b0db61af3df5cf61671c03989d311b5c1a85e0209345863c"
echo "STATIC_PAYLOAD_SHA256=034391fed753e5bc770c43db827e4b872c661b3e069267dc2a4601d11017ab58"
echo "METHOD=FULL_STATIC_RESTORE_NOT_OVERLAY"
echo "V8_TO_V12_PATCH_LAYERS=REMOVED_BY_REPLACEMENT"
echo "MAIN_PY_CHANGE=NONE"
echo "BUY_LOGIC_CHANGE=NONE"
echo "SCORING_CHANGE=NONE"
echo "SELECTION_CHANGE=NONE"
echo "WS_CHANGE=NONE"

sudo docker inspect "$APP" >/dev/null
sudo docker inspect "$GUARD" >/dev/null

MAIN_BEFORE="$(sudo docker exec "$APP" sha256sum /app/app/main.py | awk '{print $1}')"
echo "MAIN_PY_SHA256_BEFORE=$MAIN_BEFORE"

mkdir -p "$WORK/host-before" "$WORK/app-before" "$WORK/r19"
sudo cp -a "$HOST_STATIC/." "$WORK/host-before/"
sudo chown -R "$(id -u):$(id -g)" "$WORK/host-before"
sudo docker cp "$APP:/app/static/." "$WORK/app-before/"
sudo chown -R "$(id -u):$(id -g)" "$WORK/app-before"
